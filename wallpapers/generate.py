"""LUMEN OS procedural wallpaper generator.

Every wallpaper shipped with LUMEN is generated by this script, so the whole
collection is original, reproducible (fixed seeds) and can be re-rendered at
any resolution:

    python3 wallpapers/generate.py --out wallpapers/rendered --width 3840 --height 2160
    python3 wallpapers/generate.py --only lumen-dusk --width 1440 --height 900

Styles
  silk     – layered folded ribbons of light (the signature LUMEN look)
  aurora   – soft curtains of light over a dark sky
  dunes    – minimalist desert dunes (nature)
  peaks    – mountain ranges receding into haze (nature)
  gradient – mesh gradients
  mono     – minimalist graphite ribbons
"""
import argparse
import json
import math
import os

import numpy as np
from PIL import Image, ImageFilter


def hex2rgb(h):
    h = h.lstrip('#')
    return np.array([int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)], dtype=np.float32)


def srgb_to_linear(c):
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def linear_to_srgb(c):
    c = np.clip(c, 0, 1)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * np.power(c, 1 / 2.4) - 0.055)


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


class Canvas:
    """Linear-light float canvas with normalized coordinates (x in [0, aspect])."""

    def __init__(self, w, h):
        self.w, self.h = w, h
        self.aspect = w / h
        ys, xs = np.mgrid[0:h, 0:w].astype(np.float32)
        self.x = xs / h  # 0..aspect
        self.y = ys / h  # 0..1
        self.rgb = np.zeros((h, w, 3), dtype=np.float32)

    def fill_vertical(self, stops):
        """stops: list of (pos, hex)."""
        pos = np.array([s[0] for s in stops], dtype=np.float32)
        cols = np.stack([srgb_to_linear(hex2rgb(s[1])) for s in stops])
        t = self.y[..., None]
        out = np.zeros_like(self.rgb)
        for c in range(3):
            out[..., c] = np.interp(self.y, pos, cols[:, c])
        self.rgb = out

    def blend(self, color_lin, alpha):
        a = np.clip(alpha, 0, 1)[..., None]
        self.rgb = self.rgb * (1 - a) + color_lin * a

    def add(self, color_lin, amount):
        self.rgb = self.rgb + color_lin * np.clip(amount, 0, None)[..., None]

    def glow(self, cx, cy, radius, color, strength):
        d2 = (self.x - cx) ** 2 + (self.y - cy) ** 2
        self.add(srgb_to_linear(hex2rgb(color)), strength * np.exp(-d2 / (2 * radius ** 2)))

    def to_image(self, grain=0.012, seed=0, tonemap=True):
        rgb = self.rgb
        if tonemap:
            # Soft shoulder so overlapping highlights roll off like film.
            rgb = 1 - np.exp(-rgb * 1.15)
            rgb = rgb / (1 - math.exp(-1.15))
        srgb = linear_to_srgb(rgb)
        rng = np.random.default_rng(seed)
        noise = rng.normal(0, grain, srgb.shape[:2]).astype(np.float32)[..., None]
        srgb = np.clip(srgb + noise, 0, 1)
        return Image.fromarray((srgb * 255 + 0.5).astype(np.uint8), 'RGB')


def silk(cv, spec, rng):
    """Folded translucent ribbons. Each ribbon is a band around a warped curve;
    shading across the band (tanh of the signed distance) creates the fold, and
    a narrow highlight on the crest gives the satin sheen."""
    cv.fill_vertical(spec['background'])
    for g in spec.get('glows', []):
        cv.glow(*g)
    x, y = cv.x, cv.y
    for i, rb in enumerate(spec['ribbons']):
        ph = rng.uniform(0, 2 * math.pi, 4)
        amp, freq, base, width, tilt = rb['amp'], rb['freq'], rb['y'], rb['width'], rb.get('tilt', 0.0)
        # Domain warp for organic curvature.
        wx = x + 0.08 * np.sin(y * 3.1 + ph[0])
        curve = (base + tilt * (wx - cv.aspect / 2)
                 + amp * np.sin(wx * freq + ph[1])
                 + amp * 0.45 * np.sin(wx * freq * 2.13 + ph[2])
                 + amp * 0.18 * np.sin(wx * freq * 4.7 + ph[3]))
        w = width * (0.75 + 0.25 * np.sin(wx * freq * 0.7 + ph[0]))
        d = (y - curve) / w
        body = smoothstep(1.0, 0.0, np.abs(d)) ** 1.2
        fold = 0.5 + 0.5 * np.tanh(d * 2.2)          # dark → light across band
        crest = np.exp(-((d + 0.35) ** 2) / 0.012)     # satin highlight
        c0 = srgb_to_linear(hex2rgb(rb['colors'][0]))
        c1 = srgb_to_linear(hex2rgb(rb['colors'][1]))
        col = c0[None, None, :] * (1 - fold[..., None]) + c1[None, None, :] * fold[..., None]
        a = body * rb.get('opacity', 0.9)
        cv.rgb = cv.rgb * (1 - a[..., None]) + col * a[..., None]
        cv.add(srgb_to_linear(hex2rgb(rb.get('sheen', '#ffffff'))), crest * body * rb.get('sheen_amount', 0.25))
        # Soft shadow under the ribbon gives depth between layers.
        sh = np.exp(-((d - 1.15) ** 2) / 0.18) * rb.get('shadow', 0.25)
        cv.rgb *= (1 - sh[..., None] * 0.6)
    # Vignette
    vx = (x / cv.aspect - 0.5) * 2
    vy = (y - 0.5) * 2
    vig = 1 - spec.get('vignette', 0.18) * (vx ** 2 * 0.6 + vy ** 2) / 1.6
    cv.rgb *= np.clip(vig, 0, 1)[..., None]


def sheets(cv, spec, rng):
    """Overlapping sheets of luminous material, back to front. Each sheet is the
    region below a smooth wave edge. A sheet casts a soft shadow on whatever is
    behind it, carries a wide satin sheen just inside its edge and a colour
    gradient along its length — the depth cues of folded silk or paper."""
    cv.fill_vertical(spec['background'])
    for g in spec.get('glows', []):
        cv.glow(*g)
    x, y = cv.x, cv.y
    px = 1.0 / cv.h
    for sh in spec['sheets']:
        ph = rng.uniform(0, 2 * math.pi, 4)
        amp, freq = sh['amp'], sh['freq']
        wx = x + sh.get('warp', 0.06) * np.sin(x * 1.7 + ph[0])
        edge = (sh['y'] + sh.get('tilt', 0.0) * (x - cv.aspect / 2)
                + amp * np.sin(wx * freq + ph[1])
                + amp * 0.35 * np.sin(wx * freq * 2.21 + ph[2])
                + amp * 0.08 * np.sin(wx * freq * 5.3 + ph[3]))
        d = y - edge                                  # >0 inside the sheet
        # Cast shadow onto the layers behind (above the edge).
        shadow = sh.get('shadow', 0.45) * np.exp(-np.maximum(-d, 0) / sh.get('shadow_width', 0.05))
        cv.rgb *= (1 - shadow[..., None])
        # Sheet colour: gradient along x, deepening away from the edge.
        cols = [srgb_to_linear(hex2rgb(c)) for c in sh['colors']]
        t = np.clip((x / cv.aspect + 0.25 * np.sin(y * 2.0 + ph[0])), 0, 1)
        if len(cols) == 2:
            base = cols[0][None, None] * (1 - t[..., None]) + cols[1][None, None] * t[..., None]
        else:
            seg = t * (len(cols) - 1)
            i0 = np.clip(np.floor(seg).astype(int), 0, len(cols) - 2)
            f = (seg - i0)[..., None]
            C = np.stack(cols)
            base = C[i0] * (1 - f) + C[i0 + 1] * f
        deep = srgb_to_linear(hex2rgb(sh.get('deep', '#000000')))
        k = (1 - np.exp(-np.maximum(d, 0) / sh.get('depth', 0.35)))[..., None] * sh.get('deep_amount', 0.55)
        col = base * (1 - k) + deep * k
        # Satin sheen: wide soft band inside the edge + crisp rim light.
        sheen_c = srgb_to_linear(hex2rgb(sh.get('sheen', '#ffffff')))
        band = np.exp(-((d - sh.get('sheen_offset', 0.035)) ** 2) / (2 * sh.get('sheen_width', 0.018) ** 2))
        rim = np.exp(-np.maximum(d, 0) / (2.5 * px))
        col = col + sheen_c * (band * sh.get('sheen_amount', 0.22) + rim * sh.get('rim', 0.35))[..., None]
        mask = smoothstep(-0.8 * px, 0.8 * px, d)
        cv.rgb = cv.rgb * (1 - mask[..., None]) + col * mask[..., None]
    vx = (x / cv.aspect - 0.5) * 2
    vy = (y - 0.5) * 2
    vig = 1 - spec.get('vignette', 0.18) * (vx ** 2 * 0.6 + vy ** 2) / 1.6
    cv.rgb *= np.clip(vig, 0, 1)[..., None]


def aurora(cv, spec, rng):
    cv.fill_vertical(spec['background'])
    x, y = cv.x, cv.y
    for cur in spec['curtains']:
        ph = rng.uniform(0, 2 * math.pi, 3)
        base = cur['y'] + cur['amp'] * np.sin(x * cur['freq'] + ph[0]) + cur['amp'] * 0.4 * np.sin(x * cur['freq'] * 2.7 + ph[1])
        d = y - base
        # Bright lower edge, long fade upwards; vertical rays.
        edge = np.exp(-(np.maximum(d, 0) ** 2) / 0.0008) * (d > -0.5)
        up = np.exp(np.minimum(d, 0) / cur['height']) * (d <= 0)
        rays = 0.65 + 0.35 * np.sin(x * 140 + 6 * np.sin(x * 9 + ph[2])) ** 2
        intensity = (up * rays + edge * 0.6) * cur['strength']
        lo = srgb_to_linear(hex2rgb(cur['colors'][0]))
        hi = srgb_to_linear(hex2rgb(cur['colors'][1]))
        t = np.clip(-d / (cur['height'] * 3), 0, 1)[..., None]
        cv.rgb += (lo * (1 - t) + hi * t) * intensity[..., None]
    # Stars
    n = int(cv.w * cv.h / 900)
    sx = rng.integers(0, cv.w, n)
    sy = rng.integers(0, int(cv.h * 0.7), n)
    b = rng.uniform(0.2, 1.0, n) ** 3
    cv.rgb[sy, sx] += (b * 0.9)[:, None]
    for g in spec.get('glows', []):
        cv.glow(*g)
    if spec.get('horizon'):
        hz = spec['horizon']
        ridge = hz['y'] + 0.025 * np.sin(x * 3.3 + 1.2) + 0.012 * np.sin(x * 11.0) + 0.004 * np.sin(x * 37.0)
        mask = smoothstep(-0.002, 0.002, y - ridge)
        cv.blend(srgb_to_linear(hex2rgb(hz['color'])), mask)


def dunes(cv, spec, rng):
    cv.fill_vertical(spec['sky'])
    for g in spec.get('glows', []):
        cv.glow(*g)
    x, y = cv.x, cv.y
    layers = spec['layers']
    for i, L in enumerate(layers):
        ph = rng.uniform(0, 2 * math.pi, 3)
        ridge = L['y'] + L['amp'] * np.sin(x * L['freq'] + ph[0]) + L['amp'] * 0.35 * np.sin(x * L['freq'] * 2.3 + ph[1])
        # Sharp crest on one side: lit face vs shadow face.
        slope = np.cos(x * L['freq'] + ph[0])
        inside = smoothstep(-0.0015, 0.0015, y - ridge)
        lit = srgb_to_linear(hex2rgb(L['lit']))
        shade = srgb_to_linear(hex2rgb(L['shade']))
        depth = np.clip((y - ridge) / 0.25, 0, 1)[..., None]
        k = (0.5 + 0.5 * np.tanh(slope * 3))[..., None]
        col = lit * k + shade * (1 - k)
        col = col * (1 - depth * 0.35) + shade * depth * 0.35
        cv.rgb = cv.rgb * (1 - inside[..., None]) + col * inside[..., None]
        # Haze between layers
        haze = srgb_to_linear(hex2rgb(spec['haze']))
        cv.blend(haze, inside * spec.get('haze_amount', 0.1) * (len(layers) - i - 1) / len(layers))


def peaks(cv, spec, rng):
    cv.fill_vertical(spec['sky'])
    for g in spec.get('glows', []):
        cv.glow(*g)
    x, y = cv.x, cv.y
    for i, L in enumerate(spec['layers']):
        ph = rng.uniform(0, 100)
        # Fractal ridge line (sum of octaves of |sin|-based ridged noise).
        h = np.zeros_like(x[0])
        amp, freq = L['amp'], L['freq']
        xs = x[0]
        for o in range(6):
            h += amp * (1 - np.abs(np.sin(xs * freq + ph * (o + 1) * 1.7)))
            amp *= 0.48
            freq *= 2.07
        ridge = L['y'] - h
        mask = smoothstep(-0.0012, 0.0012, y - ridge[None, :])
        col = srgb_to_linear(hex2rgb(L['color']))
        fade = np.clip((y - ridge[None, :]) / L.get('fade', 0.4), 0, 1)[..., None]
        bottom = srgb_to_linear(hex2rgb(L.get('bottom', L['color'])))
        layer = col * (1 - fade) + bottom * fade
        cv.rgb = cv.rgb * (1 - mask[..., None]) + layer * mask[..., None]
        if 'mist' in L:
            mist = np.exp(-((y - ridge[None, :] - 0.06) ** 2) / 0.004) * L['mist'][1]
            cv.add(srgb_to_linear(hex2rgb(L['mist'][0])), mist)


def gradient(cv, spec, rng):
    cv.fill_vertical(spec['background'])
    for p in spec['points']:
        cx, cy, r, col, s = p
        d2 = (cv.x - cx * cv.aspect) ** 2 + (cv.y - cy) ** 2
        a = np.exp(-d2 / (2 * r ** 2)) * s
        cv.blend(srgb_to_linear(hex2rgb(col)), a)


STYLES = {'silk': silk, 'sheets': sheets, 'aurora': aurora, 'dunes': dunes, 'peaks': peaks, 'gradient': gradient}


def render(name, spec, width, height, scale_div=2):
    """Render at reduced resolution (all content is smooth), upscale with a
    high-quality filter, then add full-resolution grain."""
    rng = np.random.default_rng(spec.get('seed', 1))
    w, h = max(64, width // scale_div), max(36, height // scale_div)
    cv = Canvas(w, h)
    STYLES[spec['style']](cv, spec, rng)
    img = cv.to_image(grain=0.0, seed=spec.get('seed', 1))
    img = img.resize((width, height), Image.LANCZOS)
    if spec.get('soften'):
        img = img.filter(ImageFilter.GaussianBlur(spec['soften']))
    arr = np.asarray(img).astype(np.float32) / 255.0
    noise = np.random.default_rng(7).normal(0, spec.get('grain', 0.010), arr.shape[:2])[..., None]
    arr = np.clip(arr + noise, 0, 1)
    return Image.fromarray((arr * 255 + 0.5).astype(np.uint8), 'RGB')


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument('--specs', default=os.path.join(here, 'collection.json'))
    ap.add_argument('--out', default=os.path.join(here, 'rendered'))
    ap.add_argument('--width', type=int, default=3840)
    ap.add_argument('--height', type=int, default=2160)
    ap.add_argument('--only', action='append')
    ap.add_argument('--format', default='jpg', choices=['jpg', 'png', 'webp'])
    args = ap.parse_args()
    with open(args.specs) as f:
        collection = json.load(f)
    os.makedirs(args.out, exist_ok=True)
    for name, spec in collection['wallpapers'].items():
        if args.only and name not in args.only:
            continue
        img = render(name, spec, args.width, args.height)
        path = os.path.join(args.out, f'{name}.{args.format}')
        if args.format == 'jpg':
            img.save(path, quality=93, subsampling=0, optimize=True)
        else:
            img.save(path)
        print('wrote', path)


if __name__ == '__main__':
    main()
